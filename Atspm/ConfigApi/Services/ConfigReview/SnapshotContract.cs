using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;

namespace Utah.Udot.Atspm.ConfigApi.Services.ConfigReview;

internal static partial class SnapshotContract
{
    internal const int MaximumBytes = 512 * 1024;
    internal static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web)
    {
        PropertyNameCaseInsensitive = false,
        NumberHandling = JsonNumberHandling.Strict,
        UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow
    };

    internal static readonly (string Group, string Key)[] Collections =
    [
        ("phases", "phase"), ("phasesNotInUse", "phase"), ("overlaps", "overlap"),
        ("patterns", "pattern"), ("splitTables", "splitNumber"), ("sequences", "sequenceNumber"), ("detectors", "channel")
    ];
    private static readonly HashSet<string> Groups =
    [
        ..Collections.Select(pair => pair.Group), "phaseTiming", "phaseStructure", "configWrittenAt", "firmware"
    ];
    private static readonly HashSet<string> Structure = ["ring", "barrier", "concurrent", "inUse"];
    internal static string GroupFor(string collection, string field) => collection == "phases"
        ? Structure.Contains(field) ? "phaseStructure" : "phaseTiming"
        : collection == "phasesNotInUse" ? "phaseStructure" : collection;

    internal static ControllerSnapshot Read(byte[] payload, string location, bool external)
    {
        using var document = JsonDocument.Parse(payload, new JsonDocumentOptions { MaxDepth = 24 });
        Inspect(document.RootElement);
        if (document.RootElement.ValueKind == JsonValueKind.Object && document.RootElement.TryGetProperty("fieldSources", out _))
            throw new InvalidDataException("Field source attribution is generated by ATSPM.");
        var snapshot = document.RootElement.Deserialize<ControllerSnapshot>(Json)
            ?? throw new InvalidDataException("A snapshot object is required.");
        if (snapshot.SchemaVersion != 1 || snapshot.LocationIdentifier != location ||
            string.IsNullOrWhiteSpace(snapshot.Make) || string.IsNullOrWhiteSpace(snapshot.Model) ||
            snapshot.CollectedAt == default || snapshot.Sources is not { Length: > 0 } ||
            snapshot.Unavailable == null || snapshot.Unavailable.Distinct().Count() != snapshot.Unavailable.Length ||
            snapshot.Unavailable.Any(group => !Groups.Contains(group)))
            throw new InvalidDataException("The snapshot version, location, metadata, or availability is invalid.");

        foreach (var source in snapshot.Sources)
        {
            if (source == null || string.IsNullOrWhiteSpace(source.Kind) || string.IsNullOrWhiteSpace(source.Name) ||
                string.IsNullOrWhiteSpace(source.Decoder) || source.Groups is not { Length: > 0 } ||
                source.Groups.Any(group => !Groups.Contains(group)) ||
                (source.Kind == "file" && !Checksum().IsMatch(source.Sha256 ?? "")) ||
                (!string.IsNullOrEmpty(source.Sha256) && !Checksum().IsMatch(source.Sha256)) ||
                (external && (!source.Decoder.StartsWith("external:", StringComparison.Ordinal) ||
                    string.IsNullOrWhiteSpace(source.Decoder["external:".Length..]))))
                throw new InvalidDataException("Source metadata must provide valid groups, checksums, and decoder names.");
        }

        foreach (var (group, key) in Collections)
        {
            var declared = document.RootElement.TryGetProperty(group, out var values);
            if (!declared)
            {
                if (group is "phasesNotInUse" or "sequences")
                    continue;
                if (snapshot.Unavailable.Contains(group))
                    continue;
                throw new InvalidDataException($"Declare {group} data or list the group as unavailable.");
            }
            if (values.ValueKind != JsonValueKind.Array || values.GetArrayLength() > 512 ||
                (values.GetArrayLength() > 0 && snapshot.Unavailable.Contains(group)))
                throw new InvalidDataException($"The {group} group has invalid or contradictory data.");

            var used = new HashSet<int>();
            foreach (var value in values.EnumerateArray())
            {
                if (value.ValueKind != JsonValueKind.Object || !value.TryGetProperty(key, out var id) ||
                    !id.TryGetInt32(out var number) || number < 1 || !used.Add(number))
                    throw new InvalidDataException($"The {group} group contains an invalid or duplicate key.");
            }
        }
        if (snapshot.Phases.Any(phase => phase.InUse == true && phase.Ring is null or <= 0) ||
            snapshot.Phases.Any(phase => InvalidList(phase.Concurrent) ||
                new[] { phase.MinGreen, phase.MaxGreen1, phase.MaxGreen2, phase.Passage, phase.Walk,
                    phase.PedClear, phase.YellowChange, phase.RedClear }.Any(seconds => seconds < 0) ||
                (phase.InUse == true && phase.MinGreen == 0 && phase.MaxGreen1 == 0 && phase.MaxGreen2 == 0)) ||
            snapshot.PhasesNotInUse.Any(phase => string.IsNullOrWhiteSpace(phase.Reason) ||
                snapshot.Phases.Any(active => active.Phase == phase.Phase && active.InUse == true)) ||
            snapshot.Overlaps.Any(overlap => overlap.Type < 0 || overlap.IncludedPhases == null ||
                overlap.ModifierPhases == null || InvalidList(overlap.IncludedPhases) || InvalidList(overlap.ModifierPhases)) ||
            snapshot.Patterns.Any(pattern => pattern.Cycle <= 0 || pattern.Offset < 0 || pattern.Offset >= pattern.Cycle) ||
            snapshot.Detectors.Any(detector => detector.CallPhase < 0 || detector.SwitchPhase < 0 ||
                detector.Delay < 0 || detector.Extend < 0) ||
            snapshot.SplitTables.Any(table => table.RingSplits == null || table.RingSplits.Any(ring =>
                ring.Key < 1 || ring.Value == null || ring.Value.Any(seconds => seconds < 0))) ||
            snapshot.Sequences.Any(sequence => sequence.RingPhases == null || sequence.RingPhases.Any(ring =>
                ring.Key < 1 || ring.Value == null || InvalidList(ring.Value))) ||
            snapshot.Conflicts == null || snapshot.Notes == null ||
            snapshot.Conflicts.Any(conflict => conflict == null || !Groups.Contains(conflict.Group) ||
                string.IsNullOrWhiteSpace(conflict.Field) || conflict.Field.Length > 125 ||
                conflict.FirstValue.ValueKind == JsonValueKind.Undefined || conflict.SecondValue.ValueKind == JsonValueKind.Undefined ||
                string.IsNullOrWhiteSpace(conflict.FirstSource) || string.IsNullOrWhiteSpace(conflict.SecondSource)))
            throw new InvalidDataException("The snapshot contains invalid timing, phase, detector, or conflict data.");

        if (snapshot.Sequences.Length == 0 && snapshot.Patterns.Any(pattern => pattern.SequenceNumber is > 0 &&
            !snapshot.Sequences.Any(sequence => sequence.SequenceNumber == pattern.SequenceNumber)) &&
            !snapshot.Unavailable.Contains("sequences"))
            throw new InvalidDataException("List sequences as unavailable when a referenced definition is missing.");
        if (snapshot.SplitTables.Length == 0 && snapshot.Patterns.Any(pattern => pattern.SplitNumber is > 0 &&
            !snapshot.SplitTables.Any(table => table.SplitNumber == pattern.SplitNumber)) &&
            !snapshot.Unavailable.Contains("splitTables"))
            throw new InvalidDataException("List splitTables as unavailable when a referenced definition is missing.");

        return snapshot;
    }

    private static bool InvalidList(int[]? values) =>
        values?.Any(value => value <= 0) == true || (values != null && values.Length != values.Distinct().Count());

    private static void Inspect(JsonElement element)
    {
        switch (element.ValueKind)
        {
            case JsonValueKind.Object:
                var keys = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                foreach (var property in element.EnumerateObject())
                {
                    if (!keys.Add(property.Name))
                        throw new InvalidDataException("Duplicate JSON keys are not allowed.");
                    if (SensitiveKey().IsMatch(property.Name))
                        throw new InvalidDataException("Snapshot appears to contain credentials or account data.");
                    Inspect(property.Value);
                }
                break;
            case JsonValueKind.Array:
                foreach (var value in element.EnumerateArray())
                    Inspect(value);
                break;
            case JsonValueKind.String:
                var valueText = element.GetString()!;
                if (valueText.Length > 4096 || SensitiveText().IsMatch(valueText))
                    throw new InvalidDataException("Snapshot text exceeds its limit or appears to contain credentials or account data.");
                break;
        }
    }

    internal static string Serialize<T>(T value) => JsonSerializer.Serialize(value, Json);
    internal static JsonElement Element(string value) => JsonSerializer.Deserialize<JsonElement>(value);

    [GeneratedRegex("^[0-9a-fA-F]{64}$")]
    private static partial Regex Checksum();

    [GeneratedRegex("password|passwd|credential|community|(^token$)|bearer|access.?token|api.?key|secret|private.?key|username|account|email|authorization", RegexOptions.IgnoreCase)]
    private static partial Regex SensitiveKey();

    [GeneratedRegex(@"\b(?:bearer\s+\S+|(?:password|passwd|community|api.?key|secret|username|token)\s*[:=]|[^\s@]+@[^\s@]+\.[a-z]{2,}|[a-z]+://[^\s/]+@)", RegexOptions.IgnoreCase)]
    private static partial Regex SensitiveText();

    internal static ControllerSnapshot Merge(ControllerSnapshot? prior, ControllerSnapshot incoming)
    {
        incoming.FieldSources = AttributeFields(incoming);
        if (prior == null)
            return incoming;
        var earlier = JsonSerializer.SerializeToNode(prior, Json)!.AsObject();
        var latest = JsonSerializer.SerializeToNode(incoming, Json)!.AsObject();
        var conflicts = prior.Conflicts.Concat(incoming.Conflicts).ToList();
        var attribution = new Dictionary<string, Source[]>(prior.FieldSources);
        foreach (var (field, source) in incoming.FieldSources)
            attribution.TryAdd(field, source);
        foreach (var (collection, key) in Collections)
        {
            var previousRecords = earlier[collection]!.AsArray();
            var nextRecords = latest[collection]!.AsArray();
            var previousOrigins = Sources(prior, collection).ToArray();
            var nextOrigins = Sources(incoming, collection).ToArray();
            if (collection != "phasesNotInUse" && previousOrigins.Length != 0 && nextOrigins.Length != 0 &&
                !prior.Unavailable.Contains(collection) && !incoming.Unavailable.Contains(collection) &&
                (previousRecords.Count == 0) != (nextRecords.Count == 0))
            {
                static JsonElement Keys(JsonArray records, string keyName) =>
                    JsonSerializer.SerializeToElement(records.Select(record => record![keyName]!.GetValue<int>()));
                conflicts.Add(new(collection, $"{collection}.inventory", Keys(previousRecords, key),
                    Label(previousOrigins, null), Keys(nextRecords, key), Label(nextOrigins, null)));
                var preferPrevious = Rank(previousOrigins, collection) > Rank(nextOrigins, collection);
                if (preferPrevious)
                    latest[collection] = previousRecords.DeepClone();
                continue;
            }

            var indices = previousRecords.Select(value => (JsonObject)value!)
                .ToDictionary(value => value[key]!.GetValue<int>());
            foreach (var incomingNode in nextRecords.Select(value => (JsonObject)value!))
            {
                var number = incomingNode[key]!.GetValue<int>();
                if (!indices.TryGetValue(number, out var record))
                {
                    indices.Add(number, (JsonObject)incomingNode.DeepClone());
                    continue;
                }

                foreach (var (field, next) in incomingNode)
                {
                    if (field == "source" || next == null)
                        continue;
                    var current = record[field];
                    var group = GroupFor(collection, field);
                    var path = $"{collection}.{number}.{field}";
                    var previousFieldOrigins = Sources(prior, group, path).ToArray();
                    var nextFieldOrigins = Sources(incoming, group, path).ToArray();
                    if (current != null && !JsonNode.DeepEquals(current, next))
                    {
                        var previousSource = Label(previousFieldOrigins, record["source"]?.GetValue<string>());
                        var nextSource = Label(nextFieldOrigins, incomingNode["source"]?.GetValue<string>());
                        conflicts.Add(new(group, $"{collection}.{number}.{field}", Element(current.ToJsonString()),
                            previousSource, Element(next.ToJsonString()), nextSource));
                        if (Rank(previousFieldOrigins, group) > Rank(nextFieldOrigins, group))
                            continue;
                    }
                    attribution[path] = current != null && JsonNode.DeepEquals(current, next)
                        ? previousFieldOrigins.Concat(nextFieldOrigins).DistinctBy(source => (source.Kind, source.Name, source.Sha256, source.Decoder)).ToArray()
                        : nextFieldOrigins;
                    record[field] = next.DeepClone();
                }
                if (incomingNode["source"] != null && Rank(Sources(incoming, collection), collection) >= Rank(Sources(prior, collection), collection))
                    record["source"] = incomingNode["source"]!.DeepClone();
            }
            latest[collection] = new JsonArray(indices.Values.Select(value => (JsonNode?)value.DeepClone()).ToArray());
        }
        ReconcilePhaseUse(prior, incoming, latest, conflicts);
        var previousDate = earlier["configWrittenAt"];
        var nextDate = latest["configWrittenAt"];
        if (previousDate != null && nextDate != null && !JsonNode.DeepEquals(previousDate, nextDate))
            conflicts.Add(new("configWrittenAt", "configWrittenAt", Element(previousDate.ToJsonString()),
                Label(Sources(prior, "configWrittenAt"), null), Element(nextDate.ToJsonString()), Label(Sources(incoming, "configWrittenAt"), null)));
        if (previousDate != null && (nextDate == null || Rank(Sources(prior, "configWrittenAt"), "configWrittenAt") > Rank(Sources(incoming, "configWrittenAt"), "configWrittenAt")))
            latest["configWrittenAt"] = previousDate.DeepClone();
        latest["sources"] = JsonSerializer.SerializeToNode(prior.Sources.Concat(incoming.Sources)
            .GroupBy(source => (source.Kind, source.Name, source.Sha256, source.Decoder))
            .Select(group => group.First() with { Groups = group.SelectMany(source => source.Groups).Distinct().ToArray() }), Json);
        var unavailable = prior.Unavailable.Intersect(incoming.Unavailable).ToHashSet();
        if (latest["patterns"]!.AsArray().Any(pattern => pattern?["sequenceNumber"] is JsonValue value &&
            value.GetValue<int>() > 0 && !latest["sequences"]!.AsArray().Any(sequence =>
                sequence?["sequenceNumber"]?.GetValue<int>() == value.GetValue<int>())))
            unavailable.Add("sequences");
        latest["unavailable"] = JsonSerializer.SerializeToNode(unavailable.Order(), Json);
        latest["conflicts"] = JsonSerializer.SerializeToNode(conflicts.GroupBy(Serialize).Select(group => group.First()), Json);
        latest["notes"] = JsonSerializer.SerializeToNode(prior.Notes.Concat(incoming.Notes).Distinct(), Json);
        latest["fieldSources"] = JsonSerializer.SerializeToNode(attribution, Json);
        return latest.Deserialize<ControllerSnapshot>(Json)!;
    }

    private static void ReconcilePhaseUse(ControllerSnapshot prior, ControllerSnapshot incoming, JsonObject merged,
        List<SnapshotConflict> conflicts)
    {
        var excluded = merged["phasesNotInUse"]!.AsArray();
        var active = merged["phases"]!.AsArray().Select(row => row!.AsObject())
            .ToDictionary(row => row["phase"]!.GetValue<int>());
        foreach (var excludedPhase in excluded.ToArray())
        {
            var number = excludedPhase!["phase"]!.GetValue<int>();
            if (!active.TryGetValue(number, out var phase) || phase["inUse"]?.GetValue<bool>() != true)
                continue;
            var priorSaysActive = prior.Phases.Any(entry => entry.Phase == number && entry.InUse == true);
            var incomingSaysActive = incoming.Phases.Any(entry => entry.Phase == number && entry.InUse == true);
            var priorSaysExcluded = prior.PhasesNotInUse.Any(entry => entry.Phase == number);
            var incomingSaysExcluded = incoming.PhasesNotInUse.Any(entry => entry.Phase == number);
            if ((!priorSaysActive || !incomingSaysExcluded) && (!priorSaysExcluded || !incomingSaysActive))
                continue;
            const string group = "phaseStructure";
            var priorOrigins = Sources(prior, group).ToArray();
            var nextOrigins = Sources(incoming, group).ToArray();
            var field = $"phases.{number}.inUse";
            conflicts.Add(new(group, field, JsonSerializer.SerializeToElement(priorSaysActive),
                Label(priorOrigins, null), JsonSerializer.SerializeToElement(incomingSaysActive),
                Label(nextOrigins, null)));
            var activeWins = Rank(priorOrigins, group) > Rank(nextOrigins, group) ? priorSaysActive : incomingSaysActive;
            if (activeWins)
                excluded.Remove(excludedPhase);
            else
                phase["inUse"] = false;
        }
    }

    private static Dictionary<string, Source[]> AttributeFields(ControllerSnapshot snapshot)
    {
        var json = JsonSerializer.SerializeToNode(snapshot, Json)!.AsObject();
        var result = new Dictionary<string, Source[]>();
        foreach (var (group, key) in Collections)
        {
            foreach (var element in json[group]!.AsArray())
            {
                var row = element!.AsObject();
                var recordSource = row["source"]?.GetValue<string>();
                var number = row[key]!.GetValue<int>();
                foreach (var (field, value) in row)
                {
                    if (field == key || field == "source" || value == null)
                        continue;
                    var origins = Sources(snapshot, GroupFor(group, field)).ToArray();
                    var exact = origins.Where(source => recordSource?.StartsWith(
                        $"{source.Kind}:{source.Name}", StringComparison.OrdinalIgnoreCase) == true).ToArray();
                    result[$"{group}.{number}.{field}"] = exact.Length == 0 ? origins : exact;
                }
            }
        }
        return result;
    }

    private static string Label(IEnumerable<Source> sources, string? provided)
    {
        var labels = sources.Select(source => $"{source.Kind}:{source.Name}").ToArray();
        return labels.Length == 0 ? provided ?? "Unknown source" : string.Join(", ", labels);
    }

    internal static IEnumerable<Source> Sources(ControllerSnapshot snapshot, string group, string? field = null)
    {
        if (field != null && snapshot.FieldSources.TryGetValue(field, out var direct) && direct.Length != 0)
            return direct;
        return snapshot.Sources.Where(source => source.Groups.Contains(group) ||
            (group is "phaseTiming" or "phaseStructure" && source.Groups.Contains("phases")) ||
            (group == "configWrittenAt" && source.Kind.Equals("file", StringComparison.OrdinalIgnoreCase)));
    }

    private static int Rank(IEnumerable<Source> sources, string group)
    {
        var preferred = group is "splitTables" or "configWrittenAt" ? "file" : "ntcip";
        return sources.Any(source => source.Kind.Equals(preferred, StringComparison.OrdinalIgnoreCase)) ? 1 : 0;
    }
}
